import type { EventId } from "./types";

export type SymbolKind =
  | "bagua"
  | "star"
  | "gate"
  | "god"
  | "stem"
  | "branch"
  | "stage"
  | "flag";

export type SymbolEntry = {
  kind: SymbolKind;
  name: string;
  element?: string;
  essence: string;
  people: string[];
  places: string[];
  things: string[];
  times: string[];
  lucky: string[];
  unlucky: string[];
};

function s(
  kind: SymbolKind,
  name: string,
  essence: string,
  people: string,
  places: string,
  things: string,
  times: string,
  lucky: string,
  unlucky: string,
  element?: string,
): SymbolEntry {
  const split = (x: string) =>
    x
      .split("、")
      .map((t) => t.trim())
      .filter(Boolean);
  return {
    kind,
    name,
    element,
    essence,
    people: split(people),
    places: split(places),
    things: split(things),
    times: split(times),
    lucky: split(lucky),
    unlucky: split(unlucky),
  };
}

